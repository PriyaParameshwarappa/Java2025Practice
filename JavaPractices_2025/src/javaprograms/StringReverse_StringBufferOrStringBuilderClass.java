package javaprograms;

public class StringReverse_StringBufferOrStringBuilderClass {

	public static void main(String[] args) {
		//Has we are having reverse funcation in these class we can directly use that 
	StringBuffer sb=new StringBuffer("Selenium");
	System.out.println(sb.reverse());
		
	StringBuilder sbu=new StringBuilder("JavaSelenium");
	System.out.println(sbu.reverse());

	}

}
