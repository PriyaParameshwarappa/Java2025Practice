package javapractices2025;

public class ForLoop {

	public static void main(String[] args) {
		
		// Print 1 to 10
		
		for(int i=1;i<=10;i++) {
			System.out.println(i);
		}
		
		for(int k=10;k>=1;) {
			System.out.println(k);
			k--;
		}
		
		for(int k=10;k>=1;) {
			System.out.println(k);
			
		}

	}

}
